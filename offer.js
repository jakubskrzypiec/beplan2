// Service tiles: the blue line on top of each tile draws in when the tiles come into view.
(() => {
  const tiles = document.querySelectorAll('.svc');
  if (!tiles.length) return;
  if (!('IntersectionObserver' in window) || window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    document.documentElement.classList.add('no-svc-motion');
    return;
  }
  tiles.forEach((tile, index) => tile.style.setProperty('--d', (index * 0.12) + 's'));
  const observer = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add('is-in');
      observer.unobserve(entry.target);
    }
  }, { threshold: 0.35 });
  tiles.forEach((tile) => observer.observe(tile));
})();

// Sectors: the list picks which photo is shown and which row is open.
(() => {
  const root = document.querySelector('.sx');
  if (!root) return;
  const items = [...root.querySelectorAll('.sx-item')];
  const photos = [...root.querySelectorAll('.sx-media img')];
  const hover = window.matchMedia('(hover: hover) and (pointer: fine)');
  function open(index) {
    items.forEach((item, i) => {
      item.classList.toggle('is-active', i === index);
      item.querySelector('.sx-head').setAttribute('aria-expanded', String(i === index));
    });
    photos.forEach((photo, i) => photo.classList.toggle('is-active', i === index));
  }
  items.forEach((item, i) => {
    item.querySelector('.sx-head').addEventListener('click', () => open(i));
    item.addEventListener('mouseenter', () => { if (hover.matches) open(i); });
  });
  // Preload the other photos so the swap is instant.
  photos.forEach((photo) => { photo.loading = 'eager'; });
})();

// Process: the staircase climbs in, step by step, when it comes into view.
(() => {
  const groups = document.querySelectorAll('.stairs, .stairs-phases');
  if (!groups.length) return;
  if (!('IntersectionObserver' in window) || window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    document.documentElement.classList.add('no-svc-motion');
    return;
  }
  document.documentElement.classList.add('has-stair-motion');
  const observer = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add('is-in');
      observer.unobserve(entry.target);
    }
  }, { threshold: 0.25 });
  groups.forEach((group) => observer.observe(group));
})();
